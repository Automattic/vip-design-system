const camel = (name) => name.replace(/-([a-z])/g, (_, char) => char.toUpperCase());
const pascal = (name) =>
	name
		.split('-')
		.map((part) => part[0].toUpperCase() + part.slice(1))
		.join('');
const optionType = (options) =>
	options
		.map((value) =>
			/^(0|[1-9]\d*)(\.\d+)?$/.test(value) ? String(Number(value)) : JSON.stringify(value)
		)
		.join(' | ');

/** Generate only attribute wiring. Defaults and property declarations stay in CSS. */
export function reactWrappers(catalog, components) {
	const entries = Object.entries(catalog.classes).map(([name, entry]) => {
		const props = [
			...Object.entries(entry.settings).map(([key, setting]) => ({
				key,
				attribute: `data-${name}-${key}`,
				type: optionType(Object.keys(setting.values)),
			})),
			...Object.entries(entry.presets).map(([key, preset]) => ({
				key,
				attribute: `data-${name}-${key}`,
				type: optionType(Object.keys(preset.options)),
			})),
			...Object.entries(entry.behaviors).map(([key, behavior]) => ({
				key,
				attribute: behavior.attribute,
				type: behavior.boolean ? 'boolean' : optionType(behavior.options),
				presence: behavior.boolean === true,
			})),
		];
		return { name, props, react: entry.react };
	});
	for (const [name, entry] of Object.entries(components)) {
		if (!entry.react) continue;
		entries.push({
			name,
			react: entry.react,
			props: [
				{
					key: 'variant',
					attribute: `data-${name}-variant`,
					type: optionType([...Object.keys(entry.variants), ...Object.keys(entry.aliases)]),
				},
			],
		});
	}
	return `// Generated by Style Dictionary from configuration catalogs and component tokens. Do not edit.
import { createWrapper, type WrapperProps as PrimitiveProps } from './createWrapper';

${entries
	.map(({ name, props, react = {} }) => {
		const element = react.element ?? 'div';
		if (!['div', 'span', 'section'].includes(element))
			throw new Error(`${name}: unsupported default React element`);
		if (
			react.className !== undefined &&
			!/^[a-z][a-z0-9-]*( [a-z][a-z0-9-]*)*$/.test(react.className)
		)
			throw new Error(`${name}: invalid additional React classes`);
		const names = props.map(({ key }) => camel(key));
		if (
			new Set(names).size !== names.length ||
			names.some((key) =>
				['render', 'as', 'asChild', 'children', 'ref', 'className', 'style'].includes(key)
			)
		)
			throw new Error(`${name}: conflicting React props`);
		const attributes = props.map(({ attribute }) => attribute);
		if (new Set(attributes).size !== attributes.length)
			throw new Error(`${name}: conflicting React attributes`);
		const component = pascal(name);
		return `export type ${component}Options = {
${props.map(({ key, attribute, type }) => `/** Maps to ${attribute}. Omit to use the CSS default. */\n${camel(key)}?: ${type};`).join('\n')}
};
export type ${component}Props = PrimitiveProps<'${element}', ${component}Options>;
export const ${component} = /* @__PURE__ */ createWrapper<${component}Options, '${element}'>(
  '${component}', '${element}', '${[name, react.className].filter(Boolean).join(' ')}', {
${props.map(({ key, attribute, presence }) => `${camel(key)}: { attribute: '${attribute}'${presence ? ', presence: true' : ''} },`).join('\n')}
});
`;
	})
	.join('\n')}`;
}
